// SSE / concurrent-connection shape (POST /sse path)
// ---------------------------------------------------------------------------

describe('SSE endpoint concurrent-connection shape (POST /sse)', () => {
  it('returns 401 when no Authorization header is present', async () => {
    const req = makeRequest('/sse', {
      method: 'POST',
      body: { jsonrpc: '2.0', id: 1, method: 'ping' },
    });
    const res = await worker.fetch(req, ENV as any, makeCtx());
    expect(res.status).toBe(401);
  });

  it('returns 401 and WWW-Authenticate header when Bearer token is invalid', async () => {
    const req = makeRequest('/sse', {
      method: 'POST',
      body: { jsonrpc: '2.0', id: 1, method: 'ping' },
      headers: { Authorization: 'Bearer invalid-token' },
    });
    // Supabase service client will fail to validate — mock fetch to return 401
    global.fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({ error: 'invalid_token' }), { status: 401 }));
    const res = await worker.fetch(req, ENV as any, makeCtx());
    expect(res.status).toBe(401);
    const wwwAuth = res.headers.get('WWW-Authenticate');
    expect(wwwAuth).toBeTruthy();
    expect(wwwAuth).toContain('Bearer');
  });

  it('handles concurrent POST /sse calls independently (stateless isolation)', async () => {
    // Two concurrent requests with no auth — both must get 401 independently,
    // proving the stateless handler doesn't share mutable state between them.
    const req1 = makeRequest('/sse', {
      method: 'POST',
      body: { jsonrpc: '2.0', id: 1, method: 'ping' },
    });
    const req2 = makeRequest('/sse', {
      method: 'POST',
      body: { jsonrpc: '2.0', id: 2, method: 'ping' },
    });
    const [res1, res2] = await Promise.all([
      worker.fetch(req1, ENV as any, makeCtx()),
      worker.fetch(req2, ENV as any, makeCtx()),
    ]);
    expect(res1.status).toBe(401);
    expect(res2.status).toBe(401);
  });
});

