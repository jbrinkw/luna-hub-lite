describe('MCP tool dispatch error paths', () => {
  it('returns JSON-RPC parse error (-32700) on malformed JSON body', async () => {
    const req = new Request('https://mcp.lunahub.dev/mcp', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: 'Bearer fake-token',
      },
      body: 'not-json{{{',
    });

    // Mock Supabase getUser to return a valid user so auth passes
    global.fetch = vi.fn().mockImplementation((url: string) => {
      if (typeof url === 'string' && url.includes('/auth/v1/user')) {
        return Promise.resolve(
          new Response(JSON.stringify({ id: 'user-123', email: 'test@test.com' }), { status: 200 }),
        );
      }
      // api_keys lookup
      return Promise.resolve(new Response(JSON.stringify({ data: null, error: 'not found' }), { status: 200 }));
    });

    const res = await worker.fetch(req, ENV as any, makeCtx());
    expect(res.status).toBe(400);
    const body = (await res.json()) as any;
    expect(body.error?.code).toBe(-32700);
    expect(body.error?.message).toMatch(/parse error/i);
  });

  it('returns JSON-RPC invalid request (-32600) when method field is missing', async () => {
    // Mock valid auth
    global.fetch = vi.fn().mockImplementation((url: string) => {
      if (typeof url === 'string' && url.includes('/auth/v1/user')) {
        return Promise.resolve(
          new Response(JSON.stringify({ id: 'user-123', email: 'test@test.com' }), { status: 200 }),
        );
      }
      return Promise.resolve(new Response(JSON.stringify({ data: null, error: 'not found' }), { status: 200 }));
    });

    const req = makeRequest('/mcp', {
      method: 'POST',
      body: { jsonrpc: '2.0', id: 1 }, // missing `method`
      headers: { Authorization: 'Bearer fake-token' },
    });

    const res = await worker.fetch(req, ENV as any, makeCtx());
    expect(res.status).toBe(400);
    const body = (await res.json()) as any;
    expect(body.error?.code).toBe(-32600);
  });

  it('health endpoint is always reachable without auth', async () => {
    const req = makeRequest('/health');
    const res = await worker.fetch(req, ENV as any, makeCtx());
    expect(res.status).toBe(200);
    const text = await res.text();
    expect(text).toBe('ok');
  });

  it('CORS preflight returns 204 with correct Allow headers', async () => {
    const req = new Request('https://mcp.lunahub.dev/mcp', {
      method: 'OPTIONS',
    });
    const res = await worker.fetch(req, ENV as any, makeCtx());
    expect(res.status).toBe(204);
    expect(res.headers.get('Access-Control-Allow-Methods')).toContain('POST');
  });
});
